// 💡 自動的に予習・復習タスクを追加する機能
const autoGenerateDailyTasks = () => {
  const todayStr = DateManager.getTodayStr();
  // 当日すでに生成済みなら何もしない（Firebase sync との競合防止）
  if (S.autoTaskDate === todayStr) return;
  // フラグを先に立てる（非同期処理中の二重実行防止）
  S.autoTaskDate = todayStr;

  const days = ['日','月','火','水','木','金','土'];
  const todayDay = days[new Date().getDay()];
  const tomorrowDay = days[(new Date().getDay() + 1) % 7];

  const getSubjects = (day) => {
    const tt = S.timetable[day] || {};
    return Object.values(tt).map(v => typeof v === 'object' ? v.subj : v).filter(s => s && s.trim() !== '');
  };

  const todaySubjs = [...new Set(getSubjects(todayDay))];
  const tomorrowSubjs = [...new Set(getSubjects(tomorrowDay))];

  // done/undone 問わず既存タスクのテキスト一覧
  const existingTexts = new Set(S.tasks.map(t => t.text));

  let added = false;
  [...todaySubjs.map(s => '【復習】' + s), ...tomorrowSubjs.map(s => '【予習】' + s)].forEach(txt => {
    if (!existingTexts.has(txt)) {
      existingTexts.add(txt);
      const taskObj = { id: generateId(), text: txt, done: false, createdDate: todayStr, prio: 'mid', due: '', subj: '' };
      S.tasks.push(taskObj);
      DbService.set('tasks', taskObj);
      added = true;
    }
  });

  // autoTaskDate と追加タスクを Firebase に保存
  DbService.setMainProfile();
  if (added && typeof renderTasks === 'function') renderTasks();
};


