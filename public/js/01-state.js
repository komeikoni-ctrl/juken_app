const Store = {
  safeState: (newState) => {
    const m = JSON.parse(JSON.stringify(defaultS));
    if (!newState) return m;
    for (let k in newState) {
      if (Array.isArray(newState[k])) { m[k] = newState[k]; }
      else if (newState[k] !== null && typeof newState[k] === 'object' && m[k]) { Object.assign(m[k], newState[k]); }
      else { m[k] = newState[k]; }
    }
    if (typeof m.totalMinutes !== 'number') m.totalMinutes = 0;
    if (typeof m.sabotageCount !== 'number') m.sabotageCount = 0;
    return m;
  },
  loadLocal: () => {
    try { 
      const saved = localStorage.getItem('jukenAppData2027'); 
      return saved ? Store.safeState(JSON.parse(saved)) : Store.safeState(null);
    } catch(e) { return Store.safeState(null); }
  }
};

